import { Router } from "express";
import { Missionary } from "../../missionary/models/Missionary";
import { sendStandardResponse } from "../../../extras/helpers";
import Chalan, { IAllocationRow, IChalan, IReceipt } from "../models/Receipt";
import mongoose from "mongoose";


const receiptRouter = Router();

const toNum = (v: unknown): number => {
  const n = Number(v);
  return Number.isFinite(n) ? n : 0;
};
 
const toDate = (v: unknown): Date | undefined => {
  if (!v) return undefined;
  const d = new Date(v as string); // dayjs objects arrive as ISO strings in JSON
  return isNaN(d.getTime()) ? undefined : d;
};
 
const round2 = (n: number) => Math.round(n * 100) / 100;
 
/* ---------- Map frontend form state -> DB shape ---------- */
const mapRow = (row: any): IAllocationRow => {
  const sp = row.sponsorshipAllocationInput;
  return {
    mainPurposeCategory: row.mainPurposeCategory,
    subcategory: row.subcategory,
    amount: toNum(row.tempAmount),
    sponsorshipAllocationInput: sp
      ? {
          sponsoredTo: sp.sponsoredTo,
          period: sp.period !== undefined ? toNum(sp.period) : undefined,
          startDate: toDate(sp.startDate),
          endDate: toDate(sp.endDate),
          children: (sp.children || []).map((c: any) => ({
            childId: c._id,
            childCode: c.childCode,
            firstName: c.firstName,
            lastName: c.lastName,
            dateOfBirth: toDate(c.dateOfBirth),
          })),
        }
      : undefined,
  };
};
 
const mapReceipt = (a: any): IReceipt => {
  const rows = (a.rows || []).map(mapRow);
  const receiptAmount = toNum(a.receiptAmount);
  const allocated = rows.reduce((s: number, r: IAllocationRow) => s + r.amount, 0);
 
  return {
    receiptNo: toNum(a.receiptNo),
    receiptStatus: "pending",
    donorId: a.donorId || undefined,
    donorName: a.donorName,
    receiptAmount,
    balanceAmount: round2(receiptAmount - allocated), // computed on server
    sponsorshipAllocationInput: a.sponsorshipAllocationInput
      ? {
          gender: a.sponsorshipAllocationInput.gender,
          quantity: toNum(a.sponsorshipAllocationInput.quantity),
        }
      : undefined,
    rows,
  };
};
 
/* ---------- Validation ---------- */
const validate = (b: any, receipts: IReceipt[]): string | null => {
  if (!b.donorName) return "donorName is required";
  if (toNum(b.amount) <= 0) return "amount must be greater than 0";
//   if (!b.paymentMode) return "paymentMode is required";
//   if (b.paymentMode === "online" && !b.transactionId)
//     return "transactionId is required for online payments";
//   if (!receipts.length) return "At least one receipt is required";
 
  const receiptTotal = receipts.reduce((s, r) => s + r.receiptAmount, 0);
  if (round2(receiptTotal) > round2(toNum(b.amount)))
    return `Receipts total (${receiptTotal}) exceeds chalan amount (${b.amount})`;
 
  for (const r of receipts) {
    if (!r.donorName) return `Receipt ${r.receiptNo}: donorName is required`;
    if (!r.rows.length) return `Receipt ${r.receiptNo}: add at least one allocation row`;
  }
  return null;
};



receiptRouter.post('/', async (req, res) => {
   
   try {
    const b = req.body;
    const receipts = (b.allocation || []).map(mapReceipt);
 
    const error = validate(b, receipts);
    if (error) return res.status(400).json({ success: false, message: error });
 
    const receiptTotal = receipts.reduce((s: number, r: IReceipt) => s + r.receiptAmount, 0);
 
    const payload: Partial<IChalan> = {
      chalanStatus: 200,
 
      donorCode: b.donorCode,
      donorName: b.donorName,
      donorPhone: b.donorPhone,
      donorAddress: b.donorAddress,
 
      amount: toNum(b.amount),
      balanceAmount: round2(toNum(b.amount) - receiptTotal), // computed on server
      balanceAmountReceipt: toNum(b.balanceAmountReceipt),
      paymentMode: b.paymentMode,
      onlinePaymentType: b.paymentMode === "online" ? b.onlinePaymentType : undefined,
      transactionId: b.transactionId,
      amountCreditBank: b.amountCreditBank,
      amountDepositDate: toDate(b.amountDepositDate),
      chalanDate: toDate(b.chalanDate) || new Date(),
      creditPerson: b.creditPerson,
 
      sourceOfDonation: b.sourceOfDonation,
      promotionalOfficerName: b.promotionalOfficerName,
      remark: b.remark,
 
      receipts,
    };
 
    // chalanCode and receiptCode are generated by the pre("validate") hook
    const chalan = await Chalan.create(payload);
 
    // return res.status(201).json({
    //   success: true,
    //   message: "Chalan created successfully",
    //   data: chalan,
    // });
    sendStandardResponse<any>(res, 'OK', {
          success: true,
          data: chalan,
          message: 'Successfully created Chalan',
        });
  } catch (err: any) {
    // if (err instanceof mongoose.Error.ValidationError) {
    //   return res.status(400).json({ success: false, message: err.message });
    // }
    // if (err?.code === 11000) {
    //   return res
    //     .status(409)
    //     .json({ success: false, message: "Duplicate code, please retry", keyValue: err.keyValue });
    // }
    console.error("createChalan error:", err);
    return res.status(500).json({ success: false, message: "Internal server error" });
  }
 

});

receiptRouter.get('/', async (req, res) => {
  try {
    const chalans = await Chalan.find().sort({ createdAt: -1 }).lean();
    sendStandardResponse<any>(res, 'OK', {
      success: true,
      data: chalans,
      message: 'Successfully fetched Chalans',
    });
  }
    catch (err) {
    console.error("getChalans error:", err);
    return res.status(500).json({ success: false, message: "Internal server error" });
    }
});
export default receiptRouter;